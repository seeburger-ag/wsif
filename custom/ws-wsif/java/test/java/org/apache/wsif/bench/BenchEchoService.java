package org.apache.wsif.bench;

/**
 * Trivial target service for the Java-binding benchmark WSDL generated by
 * {@link BenchSupport}. Kept deliberately cheap so that measurements are
 * dominated by WSIF overhead, not by the service itself.
 */
public class BenchEchoService {

    public BenchEchoService() {
    }

    /**
     * Echoes its input.
     * @param in the input string
     * @return the same string
     */
    public String echo(String in) {
        return in;
    }
}

